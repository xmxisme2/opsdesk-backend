package com.opsdesk.ticket.enums;

/**
 * 工单状态动作枚举。
 *
 * <p>动作编码可由接口层根据具体路径映射，外部不允许直接传任意字符串绕过状态机。</p>
 */
public enum TicketAction {

    /** 提交工单：创建人将草稿提交到待分派。 */
    SUBMIT,

    /** 取消工单：创建人或管理员取消草稿/待分派工单。 */
    CANCEL,

    /** 分派工单：团队负责人或管理员指定处理团队/处理人。 */
    ASSIGN,

    /** 接单：处理人或具备团队处理权限的人开始处理。 */
    ACCEPT,

    /** 转派：处理人、团队负责人或管理员调整处理团队/处理人。 */
    TRANSFER,

    /** 驳回：待分派或处理中工单退回草稿。 */
    REJECT,

    /** 提交完成：当前处理人提交处理结果。 */
    COMPLETE,

    /** 确认完成：创建人确认处理结果。 */
    CONFIRM,

    /** 重新打开：创建人对待确认结果不认可，退回处理中。 */
    REOPEN,

    /** 关闭归档：创建人、团队负责人或管理员归档已完成工单。 */
    CLOSE
}
